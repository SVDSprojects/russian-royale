export const challengeBanks: Record<string, Question[]> = { editor, stress, punctuation };
export function registerChallenges(
  app: Express,
  ctx: { db: DB; requireAuth: RequestHandler; now: () => number; broadcast: () => void },
) {
  const { db } = ctx;
  db.exec(
    'CREATE TABLE IF NOT EXISTS rr_challenge_solutions(user_id TEXT NOT NULL REFERENCES users(id),question_id TEXT NOT NULL,created_at INTEGER NOT NULL,PRIMARY KEY(user_id,question_id))',
  );
  app.get('/api/challenges/:mode', ctx.requireAuth, (req, res) => {
    const questions = challengeBanks[String(req.params.mode)];
    if (!questions) throw new HttpError(404, 'Игра не найдена.');
    res.json({
      questions: questions.map(({ answer, explanation, reason, ...publicPart }) => publicPart),
      solved: db
        .prepare('SELECT question_id FROM rr_challenge_solutions WHERE user_id=?')
        .all(req.user!.id)
        .map((r) => r.question_id),
    });
  });
  app.post('/api/challenges/:mode/:id/answer', ctx.requireAuth, (req, res) => {
    const q = challengeBanks[String(req.params.mode)]?.find((q) => q.id === req.params.id);
    if (!q) throw new HttpError(404, 'Задание не найдено.');
    const answer = integer(req.body?.answer, 'Ответ', 0, q.options.length - 1);
    const reason = q.reasons ? integer(req.body?.reason, 'Обоснование', 0, q.reasons.length - 1) : undefined;
    const correct = answer === q.answer && reason === q.reason;
    const xpAwarded = transaction(db, () => {
      if (!correct) return 0;
      const added = db
        .prepare('INSERT OR IGNORE INTO rr_challenge_solutions VALUES(?,?,?)')
        .run(req.user!.id, q.id, ctx.now());
      if (!added.changes) return 0;
      db.prepare('UPDATE users SET xp=xp+5 WHERE id=?').run(req.user!.id);
      return 5;
    });
    ctx.broadcast();
    res.json({ correct, answer: q.answer, reason: q.reason, explanation: q.explanation, xpAwarded });
  });
}
